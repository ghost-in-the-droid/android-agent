"""Public Gutenberg catalog metadata only; no ebook downloads or personal library."""
import re,time,xml.etree.ElementTree as ET
from gitd.bots.common.adb import input_text_arg
PKG='com.starry.myne'
def foreground(d):
    if PKG+'/' not in d.adb('shell','dumpsys window | grep -m1 mCurrentFocus'):raise ValueError('Myne must own native focus')
def bounds(n):return list(map(int,re.findall(r'\d+',n.get('bounds',''))))
def nodes(d):
    foreground(d);root=ET.fromstring(d.dump_xml(use_portal=False));foreground(d)
    return [dict(n.attrib) for n in root.iter('node') if n.get('package')==PKG and len(bounds(n))==4 and 0<=bounds(n)[0]<bounds(n)[2]<=1080 and 0<=bounds(n)[1]<bounds(n)[3]<=2205 and n.get('enabled')!='false']
def find(ns,text=None,desc=None):return next((n for n in ns if (text is None or n.get('text')==text) and (desc is None or n.get('content-desc')==desc)),None)
def field(ns):return next((n for n in ns if n.get('class')=='android.widget.EditText'),None)
def tap(d,n):
    if n is None:raise ValueError('Expected public catalog control absent')
    foreground(d);v=bounds(n);d.tap((v[0]+v[2])//2,(v[1]+v[3])//2)
def wait(d,predicate,timeout=40):
    end=time.monotonic()+timeout
    while time.monotonic()<end:
        ns=nodes(d)
        if predicate(ns):return ns
        time.sleep(.4)
    raise ValueError('Catalog provider unavailable or expected metadata absent')
def term(value):
    value=str(value).strip()
    if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9 -]{1,69}',value):raise ValueError('Use a 2–70 character public title query')
    return value

def catalog(ns):return find(ns,desc='Home') is not None and find(ns,text='Book Details') is None and (find(ns,text='All Books') is not None or field(ns) is not None)
def cards(ns):
    if not catalog(ns):return []
    covers=sorted([n for n in ns if n.get('content-desc')=='Book cover image' and bounds(n)[3]-bounds(n)[1]>=400 and bounds(n)[3]<=2008],key=lambda n:bounds(n)[1]);result=[]
    for cover in covers:
        box=bounds(cover)
        texts=sorted([n for n in ns if n.get('class')=='android.widget.TextView' and n.get('text') and bounds(n)[0]>=430 and box[1]<=bounds(n)[1]<bounds(n)[3]<=box[3]],key=lambda n:bounds(n)[1])
        if len(texts)>=3:result.append({'title':texts[0]['text'],'author':texts[1]['text'],'language':texts[2]['text'],'subjects':[n['text'] for n in texts[3:]],'_node':texts[0]})
    return result

def results(ns):
    cs=cards(ns);edit=field(ns)
    if not edit or len(cs)<2:raise ValueError('Submitted title search with two complete catalog rows required')
    query=term(edit.get('text',''));words=query.casefold().split()
    if not all(all(w in c['title'].casefold() for w in words) for c in cs[:2]):raise ValueError('Catalog rows do not yet match the native title query')
    return {'query':query,'books':[{k:v for k,v in c.items() if k!='_node'} for c in cs[:2]],'scope':'Public Gutenberg/Gutendex catalog metadata only; no ebook or personal-library read.'}
def catalog_data(ns):
    cs=cards(ns)
    if not catalog(ns) or find(ns,text='Get Started') or find(ns,text='Thanks for installing Myne!') or len(cs)<2:raise ValueError('Two complete post-onboarding catalog rows required')
    return {'screen':'All Books','books':[{k:v for k,v in r.items() if k!='_node'} for r in cs[:2]]}
def stable_read(d,reader,timeout=12):
    """Wait for equal complete metadata reads without swallowing ownership failures."""
    deadline=time.monotonic()+timeout;previous=None
    while time.monotonic()<deadline:
        ns=nodes(d)
        try:value=reader(ns)
        except ValueError:previous=None
        else:
            if previous is not None and value==previous:return value
            previous=value
        time.sleep(.3)
    raise ValueError('Public catalog metadata did not stabilize before the deadline')

def searched(ns):
    try:return bool(results(ns))
    except ValueError:return False

def book(ns):
    download=find(ns,text='Download')
    if not find(ns,text='Book Details') or not download or field(ns):raise ValueError('Undownloaded public Book Details screen required')
    texts=sorted([n for n in ns if n.get('class')=='android.widget.TextView' and n.get('text') and bounds(n)[0]>=400 and 300<=bounds(n)[1] and bounds(n)[3]<=1000],key=lambda n:bounds(n)[1])
    if len(texts)!=2:raise ValueError('Complete book title and author required')
    badges=[n['text'] for n in sorted(ns,key=lambda n:bounds(n)[1]) if n.get('class')=='android.widget.TextView' and n.get('text') and bounds(texts[1])[3]<bounds(n)[1]<bounds(n)[3]<bounds(download)[1]]
    if len(badges)!=3:raise ValueError('Three exposed native metadata badges required')
    return {'title':texts[0]['text'],'author':texts[1]['text'],'badges':badges,'scope':'Literal native metadata badges; no inferred icon meaning or autogenerated synopsis, ebook or file read.'}

def open_catalog(d,p,c):
    d.adb('shell','am','start','-W','-S','-n',PKG+'/.MainActivity')
    for _ in range(30):
        try:foreground(d);break
        except ValueError:time.sleep(.1)
    else:raise ValueError('Myne did not acquire native focus')
    ns=wait(d,lambda ns:find(ns,text='Get Started') is not None or catalog(ns))
    if find(ns,text='Get Started'):
        if not find(ns,text='Thanks for installing Myne!') or not find(ns,text='Inbuilt Reader'):raise ValueError('Unexpected reader onboarding')
        tap(d,find(ns,text='Get Started'))
    ns=wait(d,lambda ns:catalog(ns) and len(cards(ns))>=2)
    return stable_read(d,catalog_data)
def search_books(d,p,c):
    query=term(p['query']);open_catalog(d,{},c);ns=nodes(d)
    if field(ns):raise ValueError('Start from the clean All Books catalog')
    tap(d,find(ns,desc='Search books'));ns=wait(d,lambda ns:field(ns) is not None)
    if field(ns).get('text'):raise ValueError('Empty native search field required')
    tap(d,field(ns));foreground(d);d.adb('shell','input','text',input_text_arg(query))
    ns=wait(d,searched);r=stable_read(d,results)
    if r['query']!=query:raise ValueError('Native query mismatch')
    return r
def read_results(d,p,c):return stable_read(d,results)
def open_book(d,p,c):
    ns=nodes(d);results(ns);cs=cards(ns)[:2];index=int(p['index'])
    if index<0 or index>=len(cs):raise ValueError('Choose one of the two complete exposed rows')
    chosen=cs[index];tap(d,chosen['_node']);ns=wait(d,lambda ns:find(ns,text='Book Details') is not None and find(ns,text='Download') is not None);r=book(ns)
    if r['title']!=chosen['title'] or r['author']!=chosen['author']:raise ValueError('Opened book metadata does not match selected row')
    return r
def read_book(d,p,c):return book(nodes(d))
def back_to_catalog(d,p,c):
    ns=nodes(d);book(ns);left=next((n for n in ns if n.get('content-desc')=='Go back.' and bounds(n)[2]<300),None);tap(d,left)
    ns=wait(d,lambda ns:catalog(ns) and field(ns) is None and len(cards(ns))>=2)
    return stable_read(d,catalog_data)
def catalog_ok(d,c):
    try:
        return c.result==catalog_data(nodes(d))
    except ValueError:return False
def results_ok(d,c):
    try:return c.result==results(nodes(d))
    except ValueError:return False
def book_ok(d,c):
    try:return c.result==read_book(d,{},c)
    except ValueError:return False
