"""Generate .github/CODEOWNERS: maintainer-owned platform paths plus one line per hub author.

GitHub reads CODEOWNERS only from the repo root, .github/ or docs/, so the registry workflow
writes this output to .github/CODEOWNERS (the old skillhub/CODEOWNERS location was ignored).
Later lines win: an author line overrides the catch-all for that author's folder.
"""

import argparse
import re
from pathlib import Path

MAINTAINERS = "@C-K-Loan"
# Namespaces that are NOT a contributor's GitHub login: never map them to @<name> (a stranger could own it).
MAINTAINER_NAMESPACES = ("ghost", "androidworld")
PLATFORM_PATHS = (
    "/.github/",
    "/tools/ci/",
    "/tools/build_registry.py",
    "/tools/quality.py",
    "/tools/build_codeowners.py",
    "/skillhub/scoring/",
    "/skillhub/verifier-keys.yml",
    "/skillhub/trusted-vendors.yml",
    "/docs/skillhub/security.md",
)
LOGIN = re.compile(r"[A-Za-z0-9](?:[A-Za-z0-9-]{0,37}[A-Za-z0-9])?")


def build_codeowners(root: Path) -> str:
    lines = ["# Generated by tools/build_codeowners.py (registry workflow); do not edit by hand.", f"* {MAINTAINERS}"]
    lines += [f"/skillhub/{ns}/ {MAINTAINERS}" for ns in MAINTAINER_NAMESPACES]
    lines += [f"/skillhub/scoring/ {MAINTAINERS}"]
    lines += [f"{path} {MAINTAINERS}" for path in PLATFORM_PATHS if path != "/skillhub/scoring/"]
    for author in sorted(root.iterdir()) if root.exists() else []:
        if (
            author.is_dir()
            and author.name not in (*MAINTAINER_NAMESPACES, "registry", "scoring")
            and not author.name.startswith((".", "_"))
        ):
            if not LOGIN.fullmatch(author.name):
                raise ValueError(f"Invalid GitHub author: {author.name}")
            lines.append(f"/skillhub/{author.name}/ @{author.name}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", nargs="?", type=Path, default=Path("skillhub"))
    args = parser.parse_args()
    print(build_codeowners(args.root), end="")
