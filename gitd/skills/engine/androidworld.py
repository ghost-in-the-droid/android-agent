def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "app"


def action_name(task_name: str) -> str:
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", task_name).lower()
    s = re.sub(r"[^a-z0-9_]+", "_", s).strip("_")
    return (s if s[:1].isalpha() else "task_" + s)[:64]


def _side_effects(task: AWTask) -> list[str]:
    n = task.name.lower()
    effects = set()
    if "delete" in n:
        effects.add("deletes_data")
    if "sms" in n and any(w in n for w in ("send", "reply", "resend")):
        effects.add("sends_message")
    return sorted(effects)


def _upstream_rev(root: Path) -> str:
    try:
        out = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"], capture_output=True, text=True, timeout=10)
        return out.stdout.strip() or "unknown"
    except (OSError, subprocess.SubprocessError):
        return "unknown"


def _clean(text: str) -> str:
    return text.replace(" — ", ": ").replace("—", ", ")


def render_skill(app: str, tasks: list[AWTask], packages: dict[str, str], rev: str) -> dict[str, str]:
    """Files for one skill dir: {relative name: text}."""
    slug = slugify(app)
    pkg = packages.get(app.lower(), "")
    actions, stubs, soft = [], [], []
    used_names: set[str] = set()
    for t in tasks:
        name = action_name(t.name)
        while name in used_names:
            name = (name + "_x")[:64]
        used_names.add(name)
        ref = t.template or t.doc or f"Run AndroidWorld task {t.name}"
        note = "TODO imported node: author the UI steps; AndroidWorld defines only the goal and the evaluator"
        step = (
            {"action": "launch_app", "package": pkg, "note": note}
            if pkg
            else {"action": "press_key", "key": "HOME", "note": note}
        )
        action = {
            "name": name,
            "description": _clean(
                f"AndroidWorld {t.name}"
                + (f" (complexity {t.complexity:g})" if t.complexity is not None else "")
                + f". {t.evaluator}"
            ),
            "ref_prompt": _clean(ref),
            "params": [dict(p) for p in t.params],
            "steps": [step],
            "end_state_validator": {"kind": "custom_python", "function": f"validators:{name}"},
            "test_case": {"ref_prompt_variants": [_clean(ref)], "expected_success": True},
        }
        if not action["params"]:
            action.pop("params")
        actions.append(action)
        reads = "".join(f'    _ = params.get("{p["name"]}")\n' for p in t.params)
        calls = f"\n    Upstream calls: {', '.join(t.calls)}." if t.calls else ""
        stubs.append(
            f"def {name}(device, context):\n"
            f'    """Draft of AndroidWorld {t.name} evaluator ({t.evaluator_ref or t.source}).\n\n'
            f"    {_clean(t.evaluator)}{calls}\n"
            f'    """\n'
            f"    params = context.params\n{reads}"
            f"    # TODO: port the upstream check. Until then this draft never passes.\n"
            f"    return False\n"
        )
        soft += [
            "",
            f"### `{name}({', '.join(p['name'] for p in t.params)})`",
            "",
            f"Upstream task `{t.name}` ({t.family}) in `{t.source}` line {t.line}"
            + (f", complexity {t.complexity:g}" if t.complexity is not None else "")
            + ".",
            "",
            f"Goal template: {_clean(ref)}",
            "",
            f"Evaluator ({t.evaluator_ref or 'n/a'}): {_clean(t.evaluator)}",
        ]
        if t.calls:
            soft += ["", "Upstream evaluator calls: " + ", ".join(f"`{c}`" for c in t.calls) + "."]
        if len(t.apps) > 1:
            soft += ["", "Also uses: " + ", ".join(t.apps[1:]) + "."]
        for n in t.notes:
            soft += ["", f"Note: {n}."]
    effects = sorted({e for t in tasks for e in _side_effects(t)})
    skill = {
        "name": slug,
        "version": "0.1.0",
        "author": AUTHOR,
        "description": f"AndroidWorld tasks for {app}: draft scaffolds, UI steps and validators not authored yet",
        "skill_class": "hard",
        "status": "draft",
        "license": "Apache-2.0",
        "generated_with": GENERATED_WITH,
        "side_effects": effects,
        "data_access": [],
        "fingerprint": {"os": "android", "os_version": "*", "hardware": "*", "app_package": pkg, "app_version": "*"},
        "source": {"upstream": UPSTREAM, "commit": rev, "tasks": [t.name for t in tasks]},
        "actions": actions,
    }
    if not effects:
        skill.pop("side_effects")
    header = (
        f"# {MARKER}; re-run to refresh, do not edit by hand.\n"
        f"# Derived from {UPSTREAM} @ {rev} (Apache License 2.0, see LICENSE).\n"
    )
    body = yaml.dump(skill, Dumper=_NoAliasDumper, sort_keys=False, allow_unicode=True, width=110)
    validators = (
        f'"""Draft end_state_validators for {slug}. {MARKER}.\n\n'
        f"Each function names the upstream AndroidWorld evaluator it must reproduce\n"
        f'({UPSTREAM} @ {rev}). All return False until ported.\n"""\n\n\n' + "\n\n".join(stubs)
    )
    soft_md = "\n".join(
        [
            "---",
            f"generated_with: {GENERATED_WITH}",
            f"source: {UPSTREAM} @ {rev}",
            "---",
            "",
            f"# {slug}: SOFT notes (draft)",
            "",
            f"AndroidWorld goals for {app}" + (f" (`{pkg}`)" if pkg else "") + ". Each action is a draft: the goal "
            "template and the upstream evaluator are known, the UI steps and the validator port are not. Use the "
            "evaluator notes to write `steps` and the matching `validators.py` function.",
            "",
            "## Actions",
            *soft,
            "",
        ]
    )
    readme = "\n".join(
        [
            f"# {slug}",
            "",
            f"Draft Ghost skill scaffolds for the {app} tasks of AndroidWorld ({len(tasks)} tasks). Status: **draft**; "
            "nothing here replays yet.",
            "",
            "## Attribution",
            "",
            f"Derived from [google-research/android_world]({UPSTREAM}) at commit `{rev}`, licensed under the "
            "Apache License 2.0 (a copy is in `LICENSE`). Copyright Google LLC and the AndroidWorld authors.",
            "",
            "Changes from upstream: task names, goal templates, parameter schemas and evaluator descriptions were "
            "converted to Ghost Schema v2 by `ghost skill import --androidworld`. No upstream code is vendored or "
            "executed; `validators.py` holds stubs that point at the upstream evaluators.",
            "",
            "## Tasks",
            "",
            *[f"- `{action_name(t.name)}`: {_clean(t.template or t.name)}" for t in tasks],
            "",
        ]
    )
    return {"skill.yaml": header + body, "validators.py": validators, "SOFT.md": soft_md, "README.md": readme}


def import_android_world(root: str | Path, out: str | Path, *, force: bool = False) -> list[dict]:
    """Write one draft skill per app under ``out``. Returns [{slug, path, tasks, status}]."""
    root, out = Path(root), Path(out)
    tasks = parse_android_world(root)
    packages = app_packages(root)
    rev = _upstream_rev(root)
    license_text = (root / "LICENSE").read_text() if (root / "LICENSE").is_file() else ""
    by_app: dict[str, list[AWTask]] = {}
    for t in tasks:
        by_app.setdefault(t.apps[0], []).append(t)
    results = []
    for app in sorted(by_app):
        files = render_skill(app, by_app[app], packages, rev)
        slug = slugify(app)
        d = out / slug
        existing = d / "skill.yaml"
        if existing.is_file() and MARKER not in existing.read_text() and not force:
            results.append({"slug": slug, "path": str(d), "tasks": len(by_app[app]), "status": "skipped: hand-edited"})
            continue
        d.mkdir(parents=True, exist_ok=True)
        for name, text in files.items():
            (d / name).write_text(text)
        if license_text:
            (d / "LICENSE").write_text(license_text)
        results.append({"slug": slug, "path": str(d), "tasks": len(by_app[app]), "status": "written"})
    return results
