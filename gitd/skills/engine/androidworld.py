@dataclass
class AWTask:
    name: str  # upstream task name (class or textproto name)
    family: str  # android | information_retrieval
    source: str  # repo-relative path
    line: int
    apps: list[str]
    complexity: float | None = None
    template: str = ""
    params: list[dict] = field(default_factory=list)
    evaluator: str = ""  # one-paragraph summary
    evaluator_ref: str = ""  # path:line of is_successful / success_criteria
    calls: list[str] = field(default_factory=list)
    doc: str = ""
    notes: list[str] = field(default_factory=list)


# ── static python resolution ────────────────────────────────────────────────


class _Module:
    def __init__(self, root: Path, path: Path):
        self.root, self.path = root, path
        self.rel = path.relative_to(root).as_posix()
        self.text = path.read_text()
        self.tree = ast.parse(self.text)
        self.imports: dict[str, str] = {}  # alias -> dotted module or module.symbol
        self.classes: dict[str, ast.ClassDef] = {}
        self.consts: dict[str, ast.AST] = {}
        for node in self.tree.body:
            if isinstance(node, ast.Import):
                for a in node.names:
                    self.imports[a.asname or a.name.split(".")[0]] = a.name
            elif isinstance(node, ast.ImportFrom) and node.module:
                for a in node.names:
                    self.imports[a.asname or a.name] = f"{node.module}.{a.name}"
            elif isinstance(node, ast.ClassDef):
                self.classes[node.name] = node
            elif isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
                self.consts[node.targets[0].id] = node.value


class _Resolver:
    def __init__(self, root: Path):
        self.root = root
        self._mods: dict[Path, _Module | None] = {}

    def module(self, dotted: str) -> _Module | None:
        base = self.root.joinpath(*dotted.split("."))
        for cand in (base.with_suffix(".py"), base / "__init__.py"):
            if cand.is_file():
                if cand not in self._mods:
                    try:
                        self._mods[cand] = _Module(self.root, cand)
                    except (SyntaxError, UnicodeError):
                        self._mods[cand] = None
                return self._mods[cand]
        return None

    def symbol(self, mod: _Module, expr: ast.AST):
        """Resolve a Name / Attribute to (module, ClassDef) or (module, const node)."""
        if isinstance(expr, ast.Name):
            if expr.id in mod.classes:
                return mod, mod.classes[expr.id]
            if expr.id in mod.consts:
                return mod, mod.consts[expr.id]
            target = mod.imports.get(expr.id)
            if target:
                parent, _, sym = target.rpartition(".")
                m = self.module(parent) if parent else None
                if m and sym in m.classes:
                    return m, m.classes[sym]
                if m and sym in m.consts:
                    return m, m.consts[sym]
            return None
        if isinstance(expr, ast.Attribute) and isinstance(expr.value, ast.Name):
            target = mod.imports.get(expr.value.id)
            m = self.module(target) if target else None
            if m is None and target:
                m = self.module(target.rpartition(".")[0])
            if m and expr.attr in m.classes:
                return m, m.classes[expr.attr]
            if m and expr.attr in m.consts:
                return m, m.consts[expr.attr]
        return None

    def value(self, mod: _Module, node: ast.AST):
        """Best-effort constant evaluation; None when not static."""
        try:
            return ast.literal_eval(node)
        except (ValueError, SyntaxError, TypeError):
            pass
        if isinstance(node, (ast.Name, ast.Attribute)):
            hit = self.symbol(mod, node)
            if hit and not isinstance(hit[1], ast.ClassDef):
                return self.value(hit[0], hit[1])
            return None
        if isinstance(node, (ast.Tuple, ast.List)):
            vals = [self.value(mod, e) for e in node.elts]
            return None if any(v is None for v in vals) else list(vals)
        if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
            left, right = self.value(mod, node.left), self.value(mod, node.right)
            if isinstance(left, str) and isinstance(right, str):
                return left + right
        if isinstance(node, ast.Dict):
            keys = [self.value(mod, k) for k in node.keys]
            vals = [self.value(mod, v) for v in node.values]
            if None not in keys and None not in vals:
                return dict(zip(keys, vals))
        return None

    def chain(self, mod: _Module, cls: ast.ClassDef):
        """(module, ClassDef) for the class and its resolvable bases, nearest first."""
        out, todo, seen = [], [(mod, cls)], set()
        while todo:
            m, c = todo.pop(0)
            if (m.rel, c.name) in seen:
                continue
            seen.add((m.rel, c.name))
            out.append((m, c))
            for b in c.bases:
                hit = self.symbol(m, b)
                if hit and isinstance(hit[1], ast.ClassDef):
                    todo.append(hit)
        return out

    def attr(self, chain, name: str):
        for m, c in chain:
            for st in c.body:
                targets = []
                if isinstance(st, ast.Assign):
                    targets = [t.id for t in st.targets if isinstance(t, ast.Name)]
                    value = st.value
                elif isinstance(st, ast.AnnAssign) and isinstance(st.target, ast.Name) and st.value is not None:
                    targets, value = [st.target.id], st.value
                if name in targets:
                    return m, self.value(m, value), st
        return None, None, None

    def method(self, chain, name: str):
        for m, c in chain:
            for st in c.body:
                if isinstance(st, ast.FunctionDef) and st.name == name:
                    return m, st
        return None, None


def _dotted(node: ast.AST) -> str:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        inner = _dotted(node.value)
        return f"{inner}.{node.attr}" if inner else node.attr
    return ""


def _evaluator_summary(mod: _Module, fn: ast.FunctionDef) -> tuple[str, list[str]]:
    calls = []
    for node in ast.walk(fn):
        if isinstance(node, ast.Call):
            name = _dotted(node.func)
            if (
                name
                and not name.startswith(("super", "self._params", "len", "int", "str", "float", "any", "all"))
                and name not in calls
            ):
                calls.append(name)
    src = ast.get_source_segment(mod.text, fn) or ""
    sources = [label for key, label in _STATE_HINTS if key in src]
    seen, uniq = set(), []
    for s in sources:
        if s not in seen:
            seen.add(s)
            uniq.append(s)
    doc = ast.get_docstring(fn) or ""
    summary = "Upstream checks " + (", ".join(uniq) if uniq else "device state") + "."
    if doc:
        summary += " " + " ".join(doc.split())
    return summary, calls[:10]


def _placeholder_name(node: ast.AST) -> str:
    if isinstance(node, ast.Subscript):
        key = node.slice
        if isinstance(key, ast.Constant) and isinstance(key.value, str):
            name = key.value
        else:
            name = _dotted(key).split(".")[-1] or _placeholder_name(node.value)
    elif isinstance(node, ast.Call):
        name = _dotted(node.func).split(".")[-1]
    else:
        name = _dotted(node).split(".")[-1]
    name = re.sub(r"[^A-Za-z0-9_]", "_", name).strip("_").lower()
    return name if name[:1].isalpha() else "value"


def _goal_template(res: "_Resolver", mod: _Module, fn: ast.FunctionDef) -> str:
    """Template text from a `goal` property's first return: literals kept, module str
    constants inlined, any other interpolation becomes a {placeholder}."""
    ret = next((n.value for n in ast.walk(fn) if isinstance(n, ast.Return) and n.value is not None), None)

    def render(node) -> str | None:
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            return node.value
        if isinstance(node, ast.JoinedStr):
            parts = []
            for v in node.values:
                if isinstance(v, ast.Constant):
                    parts.append(str(v.value))
                elif isinstance(v, ast.FormattedValue):
                    const = res.value(mod, v.value)
                    parts.append(const if isinstance(const, str) else "{" + _placeholder_name(v.value) + "}")
            return "".join(parts)
        if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
            left, right = render(node.left), render(node.right)
            return left + right if left is not None and right is not None else None
        const = res.value(mod, node) if node is not None else None
        return const if isinstance(const, str) else None

    return " ".join((render(ret) or "").split())


def _params_from(schema, template: str) -> list[dict]:
    params, names = [], set()
    if isinstance(schema, dict):
        required = set(schema.get("required") or [])
        for pname, spec in (schema.get("properties") or {}).items():
            ptype = _JSON_TYPES.get((spec or {}).get("type"), "str") if isinstance(spec, dict) else "str"
            if isinstance(spec, dict) and spec.get("type") == "array":
                ptype = "list[str]"
            params.append({"name": pname, "type": ptype, "required": pname in required})
            names.add(pname)
    for pname in _PLACEHOLDER.findall(template or ""):
        if pname not in names:
            params.append({"name": pname, "type": "str", "required": True})
            names.add(pname)
    return params


def parse_single_tasks(root: Path) -> list[AWTask]:
    res = _Resolver(root)
    reg = res.module("android_world.registry")
    if reg is None:
        raise ValueError(f"{root}: android_world/registry.py not found (is this an android_world checkout?)")
    tasks_node = None
    for node in ast.walk(reg.tree):
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "_TASKS" for t in node.targets):
            tasks_node = node.value
    if not isinstance(tasks_node, (ast.Tuple, ast.List)):
        raise ValueError("registry.py: _TASKS tuple not found")
    out = []
    for elt in tasks_node.elts:
        hit = res.symbol(reg, elt)
        label = _dotted(elt)
        if not hit or not isinstance(hit[1], ast.ClassDef):
            raise ValueError(f"registry.py: cannot resolve task {label}")
        mod, cls = hit
        chain = res.chain(mod, cls)
        _, apps, _ = res.attr(chain, "app_names")
        _, complexity, _ = res.attr(chain, "complexity")
        _, schema, _ = res.attr(chain, "schema")
        _, template, _ = res.attr(chain, "template")
        notes = []
        if isinstance(apps, (tuple, list)):
            apps = [str(a) for a in apps]
        if not isinstance(apps, list) or not [a for a in apps if a]:
            notes.append("app_names not static upstream; app inferred from the module name")
            apps = [Path(mod.rel).stem.replace("_", " ")]
        apps = [a for a in apps if a]
        if not isinstance(template, str) or not template.strip():
            gmod, gfn = res.method(chain, "goal")
            goal = (
                _goal_template(res, gmod, gfn)
                if gfn is not None and gmod.rel != "android_world/task_evals/task_eval.py"
                else ""
            )
            if goal:
                notes.append("goal built at runtime upstream; template reconstructed from the goal property")
                template = goal
            else:
                notes.append("goal not static upstream; ref_prompt falls back to the task docstring")
                template = ""
        if schema is None:
            notes.append("schema not static upstream; params taken from the template placeholders")
        fmod, fn = res.method(chain, "is_successful")
        if fn is not None:
            evaluator, calls = _evaluator_summary(fmod, fn)
            eref = f"{fmod.rel}:{fn.lineno}"
        else:
            evaluator, calls, eref = "Upstream evaluator not found statically.", [], ""
        out.append(
            AWTask(
                name=cls.name,
                family="android",
                source=mod.rel,
                line=cls.lineno,
                apps=apps,
                complexity=complexity if isinstance(complexity, (int, float)) else None,
                template=" ".join(template.split()),
                params=_params_from(schema, template),
                evaluator=evaluator,
                evaluator_ref=eref,
                calls=calls,
                doc=" ".join((ast.get_docstring(cls) or "").split()),
                notes=notes,
            )
        )
    return out


# ── textproto (information retrieval) ───────────────────────────────────────

_TOKEN = re.compile(r'\s*(?:(#[^\n]*)|("(?:[^"\\]|\\.)*")|([{}:])|([^\s{}:"#]+))')


def parse_textproto(text: str) -> list:
    """Minimal textproto reader: list of (key, value); value is a scalar or a nested list."""
    tokens, pos = [], 0
    while pos < len(text):
        m = _TOKEN.match(text, pos)
        if not m or m.end() == pos:
            break
        pos = m.end()
        if m.group(1):
            continue
        if m.group(2):
            tokens.append(("str", json.loads(m.group(2))))
        elif m.group(3):
            tokens.append((m.group(3), m.group(3)))
        elif m.group(4):
            tokens.append(("word", m.group(4)))
    i = 0

    def block():
        nonlocal i
        items = []
        while i < len(tokens) and tokens[i][0] != "}":
            key = tokens[i][1]
            i += 1
            if i < len(tokens) and tokens[i][0] == ":":
                i += 1
            if i < len(tokens) and tokens[i][0] == "{":
                i += 1
                items.append((key, block()))
                i += 1  # closing }
            elif i < len(tokens):
                items.append((key, tokens[i][1]))
                i += 1
        return items

    return block()


def _first(items, key):
    for k, v in items:
        if k == key:
            return v
    return None


def _find_all(items, key):
    out = []
    for k, v in items:
        if k == key:
            out.append(v)
        if isinstance(v, list):
            out += _find_all(v, key)
    return out


def parse_ir_tasks(root: Path) -> list[AWTask]:
    f = root / "android_world/task_evals/information_retrieval/proto/tasks.textproto"
    if not f.is_file():
        return []
    rel = f.relative_to(root).as_posix()
    text = f.read_text()
    out = []
    for key, task in parse_textproto(text):
        if key != "tasks" or not isinstance(task, list):
            continue
        name = str(_first(task, "name") or "")
        prompt = " ".join(str(_first(task, "prompt") or "").split())
        apps = [a for a in _find_all(task, "app_name") if isinstance(a, str)][:1] or ["information retrieval"]
        crit = _first(task, "success_criteria") or []
        exps = [e for k, e in crit if k == "expectations" and isinstance(e, list)]
        fields_ = [str(x) for e in exps for x in _find_all(e, "field_name")]
        match = [str(x) for e in exps for x in _find_all(e, "match_type")]
        evaluator = (
            "Answer task: the agent's final answer is compared with the seeded app state"
            + (f" ({', '.join(sorted(set(fields_)))})" if fields_ else "")
            + (f" using {', '.join(sorted(set(match)))}" if match else "")
            + "."
        )
        line = text[: text.find(f'name: "{name}"')].count("\n") + 1 if name else 0
        cx = _first(task, "complexity")
        out.append(
            AWTask(
                name=name,
                family="information_retrieval",
                source=rel,
                line=line,
                apps=apps,
                complexity=float(cx) if cx not in (None, "") and re.match(r"^\d+(\.\d+)?$", str(cx)) else None,
                template=prompt,
                params=_params_from(None, prompt),
                evaluator=evaluator,
                evaluator_ref=f"{rel}:{line}",
                calls=[],
                notes=["Answer task: the end state is the agent's answer (context.result['answer']), not a screen"],
            )
        )
    return out


def app_packages(root: Path) -> dict[str, str]:
    """App name (each '|' alias) -> package, from adb_utils._PATTERN_TO_ACTIVITY."""
    mod = _Resolver(Path(root)).module("android_world.env.adb_utils")
    out: dict[str, str] = {}
    if mod is None:
        return out
    node = mod.consts.get("_PATTERN_TO_ACTIVITY")
    if isinstance(node, ast.Call) and node.args:
        node = node.args[0]
    if not isinstance(node, ast.Dict):
        return out
    for k, v in zip(node.keys, node.values):
        try:
            pattern, activity = ast.literal_eval(k), ast.literal_eval(v)
        except (ValueError, SyntaxError):
            continue
        for alias in str(pattern).split("|"):
            out[alias.strip().lower()] = str(activity).split("/")[0]
    return out


def parse_android_world(root: str | Path) -> list[AWTask]:
    root = Path(root)
    return parse_single_tasks(root) + parse_ir_tasks(root)


