"""`ghost skill import --androidworld <checkout>`: AndroidWorld tasks -> Schema v2 draft scaffolds.

Reads a google-research/android_world checkout STATICALLY (``ast`` + a small
textproto reader). Nothing upstream is imported, installed or executed.

Sources:
* ``android_world/registry.py`` ``_TASKS``: the single + composite task classes
  (``app_names``, ``complexity``, ``schema``, ``template``, ``is_successful``),
  resolved through base classes and module constants across modules.
* ``android_world/task_evals/information_retrieval/proto/tasks.textproto``:
  the information-retrieval tasks (``name``, ``prompt``, ``complexity``,
  ``app_name``, ``success_criteria``).
* ``android_world/env/adb_utils.py`` ``_PATTERN_TO_ACTIVITY``: app name -> package.

Output: one skill per primary app at ``<out>/<app>/`` (author ``androidworld``, default ``skillhub/androidworld/``) with one
action per task. AndroidWorld defines goals and evaluators, not UI steps, so
each action is a draft: ``ref_prompt`` from the task template, params from the
schema / template placeholders, a single TODO-noted step, and an
``end_state_validator`` pointing at a ``validators.py`` stub that documents the
upstream evaluator and returns False until ported. Skill-level
``status: draft``, ``license: Apache-2.0`` (upstream LICENSE copied, README
carries the attribution), ``generated_with: ghost skill import --androidworld``.
"""

