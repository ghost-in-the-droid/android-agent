class _NoAliasDumper(yaml.SafeDumper):
    """Shared dicts/lists (inherited params, success validators) are written out in full, no &anchors."""

    def ignore_aliases(self, data):
        return True


def _strip_block(text: str) -> str:
    if BEGIN not in text:
        return text
    head, _, rest = text.partition(BEGIN)
    _, _, tail = rest.partition(END)
    return head.rstrip("\n") + "\n" + tail.lstrip("\n")


def _author(skill_dir: Path, raw: dict, author: str | None) -> str | None:
    if raw.get("author"):
        return str(raw["author"])
    if author:
        return author
    if skill_dir.resolve().parent.parent.name == "skillhub":
        return skill_dir.resolve().parent.name
    return None


def migrate_skill(path: str | Path, *, author: str | None = None, dry_run: bool = False) -> MigrateResult:
    """Migrate one v1 skill dir in place. Never raises for a bad skill; returns status legacy."""
    from gitd.skills.engine.loader import load_skill

    skill_dir = Path(path)
    yaml_path = skill_dir / "skill.yaml"
    if not yaml_path.is_file():
        return MigrateResult(skill_dir, "legacy", "no skill.yaml")
    original = yaml_path.read_text()
    base_text = _strip_block(original)
    try:
        raw = yaml.safe_load(base_text) or {}
    except yaml.YAMLError as e:
        return MigrateResult(skill_dir, "legacy", f"skill.yaml does not parse: {e}")
    if raw.get("actions") and BEGIN not in original:
        return MigrateResult(skill_dir, "already_v2", actions=[a.get("name") for a in raw["actions"]])

    slug = str(raw.get("name") or skill_dir.name)
    who = _author(skill_dir, raw, author)
    if not who:
        return MigrateResult(skill_dir, "legacy", "author unknown: pass --author <github-handle>")

    helpers = None
    targets: list[V1Target] = []
    skipped: list[str] = []
    if _py_files(skill_dir) or (skill_dir / "workflows" / "recorded.json").is_file():
        targets = _v1_targets(skill_dir, raw, skipped)
        if not targets:
            return MigrateResult(skill_dir, "legacy", "no exported v1 Action/Workflow classes or recorded.json found")
        existing = skill_dir / "helpers.py"
        if existing.is_file() and HELPERS_MARK not in existing.read_text():
            return MigrateResult(skill_dir, "legacy", "helpers.py exists and was not generated by migrate")
        actions = _python_actions(targets)
        helpers = _helpers_py(slug, targets)
        skill_class = raw.get("skill_class") or "hard"
    elif (skill_dir / "FLOW.md").is_file() and raw.get("entry_url"):
        actions = [_soft_action(skill_dir, raw, slug)]
        skill_class = "soft"
    else:
        return MigrateResult(skill_dir, "legacy", "neither v1 Python classes, recorded.json, nor FLOW.md + entry_url")

    block = {
        "author": who,
        "skill_class": skill_class,
        "license": "MIT",
        "generated_with": GENERATED_WITH,
        "fingerprint": _fingerprint(raw),
        "actions": actions,
    }
    block = {k: v for k, v in block.items() if k not in raw or k == "skill_class" and raw.get(k) != v}
    if "skill_class" in raw and "skill_class" in block:
        return MigrateResult(skill_dir, "legacy", f"skill_class {raw['skill_class']!r} conflicts with {skill_class!r}")
    body = yaml.dump(block, Dumper=_NoAliasDumper, sort_keys=False, allow_unicode=True, width=100)
    new_text = f"{base_text.rstrip()}\n\n{BEGIN}\n{body}{END}\n"
    names = [a["name"] for a in actions]
    if dry_run:
        return MigrateResult(skill_dir, "migrated", "dry run", names, skipped=skipped)

    soft_path = skill_dir / "SOFT.md"
    old_soft = soft_path.read_text() if soft_path.is_file() else None
    soft = _soft_md(skill_dir, raw, slug, actions, targets) if old_soft is None or SOFT_MARK in old_soft else None
    helpers_path = skill_dir / "helpers.py"
    old_helpers = helpers_path.read_text() if helpers_path.is_file() else None
    yaml_path.write_text(new_text)
    if helpers is not None:
        helpers_path.write_text(helpers)
    if soft is not None:
        soft_path.write_text(soft)
    try:
        load_skill(skill_dir)
    except Exception as e:                     # roll back: never leave a broken skill.yaml behind
        yaml_path.write_text(original)
        if helpers is not None:
            if old_helpers is None:
                helpers_path.unlink(missing_ok=True)
            else:
                helpers_path.write_text(old_helpers)
        if soft is not None:
            if old_soft is None:
                soft_path.unlink(missing_ok=True)
            else:
                soft_path.write_text(old_soft)
        return MigrateResult(skill_dir, "legacy", f"generated v2 block does not validate: {e}")
    written = [yaml_path] + ([helpers_path] if helpers is not None else []) + ([soft_path] if soft is not None else [])
    return MigrateResult(skill_dir, "migrated", actions=names, written=written, skipped=skipped)
