def _v1_package():
    """Import the v1 package as gitd.skills.<slug> (its own imports use that name)."""
    name = f"gitd.skills.{{SLUG}}"
    if name in sys.modules:
        return sys.modules[name]
    try:
        return importlib.import_module(name)          # source checkout: gitd.skills path includes skillhub/ghost
    except ImportError:
        spec = importlib.util.spec_from_file_location(
            name, SKILL_DIR / "__init__.py", submodule_search_locations=[str(SKILL_DIR)])
        module = importlib.util.module_from_spec(spec)
        sys.modules[name] = module
        spec.loader.exec_module(module)
        return module


def _run_recorded(device, params):
    import yaml

    from gitd.skills.base import RecordedWorkflow
    from gitd.skills.platforms import skill_target_for_device

    steps = json.loads((SKILL_DIR / "workflows" / "recorded.json").read_text())
    meta = yaml.safe_load((SKILL_DIR / "skill.yaml").read_text()) or {{}}
    wf = RecordedWorkflow(device, steps, params)
    wf.app_package = skill_target_for_device(meta, getattr(device, "serial", str(device))) or ""
    wf._popup_detectors = meta.get("popup_detectors") or None
    return wf.run()


def _run(v2_name, device, params, context):
    kind, v1_name = V1_TARGETS[v2_name]
    params = {{k: v for k, v in (params or {{}}).items() if v is not None}}
    if kind == "recorded":
        res = _run_recorded(device, params)
    else:
        skill = _v1_package().load()
        get = skill.get_workflow if kind == "workflow" else skill.get_action
        obj = get(v1_name, device, **params)
        if obj is None:
            return {{"success": False, "error": f"v1 {{kind}} {{v1_name!r}} not found"}}
        res = obj.run()
    ok = bool(getattr(res, "success", False))
    data = dict(getattr(res, "data", None) or {{}})
    data["v1_ok"] = ok
    return {{"success": ok, "error": getattr(res, "error", "") or "", "data": data}}


def v1_ok(device, context):
    """end_state_validator: the wrapped v1 run reported success."""
    return bool(context.result.get("v1_ok"))


