// Precompile src/lib/hub/skill.schema.json into a standalone ajv validator so
// the /skills/validate page ships a few KB of generated code instead of the
// ajv compiler (~150 KB). Runs as `prebuild` and `predev`; the output is
// gitignored so it can never drift from the schema hub-migrate regenerates.
import { readFileSync, writeFileSync } from 'node:fs';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const schemaPath = new URL('../src/lib/hub/skill.schema.json', import.meta.url);
const outPath = new URL('../src/lib/hub/skill.validate.generated.js', import.meta.url);
const schema = JSON.parse(readFileSync(schemaPath, 'utf8'));
const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true } });
const validate = ajv.compile(schema);
// ajv's ESM output still require()s its two runtime helpers; hoist them to imports.
const imports = [];
const code = standaloneCode(ajv, validate).replace(
	/const (func\d+) = require\("([^"]+)"\)\.default/g,
	(_, name, mod) => {
		// CJS module: Vite unwraps `.default`, plain Node ESM does not. Handle both.
		imports.push(`import ${name}_m from '${mod}.js';\nconst ${name} = ${name}_m.default ?? ${name}_m;`);
		return '';
	},
);
writeFileSync(outPath, `// GENERATED by scripts/compile-skill-schema.mjs from skill.schema.json. Do not edit.\n${imports.join('\n')}\n${code}\n`);
console.log(`compiled skill schema -> ${outPath.pathname} (${code.length} bytes)`);
